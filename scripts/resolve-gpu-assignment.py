#!/usr/bin/env python3
"""Resolve and report the per-service GPU assignment for AEC Demo Portable.

The portable demo runs three GPU consumers:

  * Ollama, hosting the Hermes agent model
  * ComfyUI, hosting the Flux.2 Klein image models
  * Blender, running Cycles for the beauty/depth/segmentation passes

On a single-GPU DGX Spark all three share the one device and nothing is
pinned. On a multi-GPU workstation the agent model is isolated on its own
device so a long Cycles render or a Flux sampling pass cannot evict it, and
Blender and ComfyUI share the remaining device together with the desktop.

Assignment is written to config/gpu-assignment.env by `--write`, read from
AEC_PORTABLE_LLM_GPU / AEC_PORTABLE_RENDER_GPU when those are already set, and
otherwise derived from nvidia-smi. GPUs are addressed by UUID: PCI enumeration
order is stable, but index-based pinning silently retargets if a card is moved
or added.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parent.parent
ASSIGNMENT_FILE = ROOT / "config" / "gpu-assignment.env"


def query_gpus() -> list[dict[str, str]]:
    """Return the local NVIDIA GPUs in PCI bus order."""
    try:
        completed = subprocess.run(
            [
                "nvidia-smi",
                "--query-gpu=index,uuid,name,pci.bus_id,display_active",
                "--format=csv,noheader",
            ],
            check=True,
            capture_output=True,
            text=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        raise RuntimeError(f"nvidia-smi is unavailable: {exc}") from exc
    gpus: list[dict[str, str]] = []
    for line in completed.stdout.splitlines():
        parts = [part.strip() for part in line.split(",")]
        if len(parts) < 5:
            continue
        gpus.append(
            {
                "index": parts[0],
                "uuid": parts[1],
                "name": parts[2],
                "bus_id": parts[3],
                "display_active": parts[4],
            }
        )
    if not gpus:
        raise RuntimeError("nvidia-smi reported no GPUs")
    return gpus


def resolve(gpus: list[dict[str, str]]) -> tuple[str, str, str]:
    """Return (llm_gpu, render_gpu, reason) as UUIDs.

    Blender and ComfyUI are deliberately placed on the display GPU: the
    Blender viewport already composites there, so keeping Cycles on the same
    device avoids a cross-device copy of every rendered frame.
    """
    override_llm = os.environ.get("AEC_PORTABLE_LLM_GPU", "").strip()
    override_render = os.environ.get("AEC_PORTABLE_RENDER_GPU", "").strip()
    if override_llm and override_render:
        return override_llm, override_render, "explicit_override"

    if len(gpus) == 1:
        uuid = gpus[0]["uuid"]
        return uuid, uuid, "single_gpu_shared"

    display = [gpu for gpu in gpus if gpu["display_active"].lower() == "enabled"]
    render_gpu = display[0] if display else gpus[-1]
    headless = [gpu for gpu in gpus if gpu["uuid"] != render_gpu["uuid"]]
    llm_gpu = headless[0]
    reason = "display_gpu_renders" if display else "last_gpu_renders"
    return llm_gpu["uuid"], render_gpu["uuid"], reason


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write",
        action="store_true",
        help="write config/gpu-assignment.env instead of only reporting",
    )
    args = parser.parse_args()

    gpus = query_gpus()
    for gpu in gpus:
        print(
            f"GPU_PRESENT index={gpu['index']} uuid={gpu['uuid']} "
            f"bus={gpu['bus_id']} display={gpu['display_active']} name={gpu['name']}"
        )
    llm_gpu, render_gpu, reason = resolve(gpus)
    print(f"GPU_COUNT={len(gpus)}")
    print(f"GPU_ASSIGNMENT_REASON={reason}")
    print(f"AEC_PORTABLE_LLM_GPU={llm_gpu}")
    print(f"AEC_PORTABLE_RENDER_GPU={render_gpu}")

    if args.write:
        ASSIGNMENT_FILE.parent.mkdir(parents=True, exist_ok=True)
        ASSIGNMENT_FILE.write_text(
            "# Generated by scripts/resolve-gpu-assignment.py --write\n"
            "# Per-service GPU pinning for this specific machine. UUIDs are\n"
            "# machine-specific; never copy this file to another host.\n"
            f"AEC_PORTABLE_LLM_GPU={llm_gpu}\n"
            f"AEC_PORTABLE_RENDER_GPU={render_gpu}\n",
            encoding="utf-8",
        )
        print(f"GPU_ASSIGNMENT_WRITTEN={ASSIGNMENT_FILE}")


if __name__ == "__main__":
    main()
