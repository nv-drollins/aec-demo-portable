#!/usr/bin/env bash
# Pin the Ollama service to the GPU reserved for the Hermes agent model.
#
# On a single-GPU DGX Spark this is a no-op: the resolver reports the same
# device for both roles and no selector is written, so Ollama keeps its default
# behaviour. On a multi-GPU workstation it writes a systemd drop-in so the
# agent model cannot be evicted by Blender or ComfyUI work.
set -euo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
OVERRIDE_DIR="/etc/systemd/system/ollama.service.d"
OVERRIDE="$OVERRIDE_DIR/10-aec-portable-gpu.conf"

if ! command -v systemctl >/dev/null 2>&1; then
    echo "OLLAMA_GPU_PIN_SKIPPED=no_systemd"
    exit 0
fi
if ! systemctl list-unit-files ollama.service >/dev/null 2>&1; then
    echo "OLLAMA_GPU_PIN_SKIPPED=ollama_service_not_installed"
    exit 0
fi

eval "$(python3 "$ROOT/scripts/resolve-gpu-assignment.py" --write |
    grep -E '^(AEC_PORTABLE_LLM_GPU|AEC_PORTABLE_RENDER_GPU)=')"

if [[ -z "${AEC_PORTABLE_LLM_GPU:-}" ]]; then
    echo "OLLAMA_GPU_PIN_FAILED=resolver_returned_no_llm_gpu" >&2
    exit 1
fi

OLLAMA_CONTEXT_LENGTH="${AEC_PORTABLE_OLLAMA_CONTEXT_LENGTH:-262144}"

if [[ "$AEC_PORTABLE_LLM_GPU" == "$AEC_PORTABLE_RENDER_GPU" ]]; then
    # Single GPU: do not constrain Ollama, but still apply the demo's context
    # and keep-alive policy so behaviour matches the multi-GPU path.
    SELECTOR_LINE="# single GPU on this host; CUDA_VISIBLE_DEVICES intentionally unset"
    echo "OLLAMA_GPU_PIN_MODE=shared_single_gpu"
else
    SELECTOR_LINE="Environment=\"CUDA_VISIBLE_DEVICES=$AEC_PORTABLE_LLM_GPU\""
    echo "OLLAMA_GPU_PIN_MODE=dedicated gpu=$AEC_PORTABLE_LLM_GPU"
fi

sudo mkdir -p "$OVERRIDE_DIR"
sudo tee "$OVERRIDE" >/dev/null <<EOF
# Generated by scripts/configure-ollama-gpu.sh for AEC Demo Portable.
# UUIDs are machine-specific; do not copy this file to another host.
[Service]
Environment="CUDA_DEVICE_ORDER=PCI_BUS_ID"
$SELECTOR_LINE
Environment="OLLAMA_CONTEXT_LENGTH=$OLLAMA_CONTEXT_LENGTH"
Environment="OLLAMA_KEEP_ALIVE=-1"
Environment="OLLAMA_VULKAN=0"
EOF

sudo systemctl daemon-reload
sudo systemctl restart ollama

# Probe without curl: a minimal Ubuntu desktop install does not ship it, and
# this script runs during offline installation where nothing can be fetched.
# Python 3 is guaranteed present because the installers depend on it.
ollama_responding() {
    python3 - <<'PY' >/dev/null 2>&1
import sys
import urllib.request

try:
    with urllib.request.urlopen("http://127.0.0.1:11434/api/tags", timeout=3) as response:
        sys.exit(0 if response.status == 200 else 1)
except Exception:
    sys.exit(1)
PY
}

for _ in $(seq 1 60); do
    if ollama_responding; then
        break
    fi
    sleep 1
done
if ! ollama_responding; then
    echo "OLLAMA_GPU_PIN_FAILED=service_did_not_return endpoint=http://127.0.0.1:11434" >&2
    exit 1
fi

echo "OLLAMA_GPU_PIN_APPLIED=$OVERRIDE"
systemctl show ollama -p Environment --value |
    tr ' ' '\n' |
    grep -E 'CUDA_VISIBLE_DEVICES|CUDA_DEVICE_ORDER|OLLAMA_CONTEXT_LENGTH|OLLAMA_KEEP_ALIVE|OLLAMA_VULKAN' |
    sed 's/^/OLLAMA_ENV=/'
